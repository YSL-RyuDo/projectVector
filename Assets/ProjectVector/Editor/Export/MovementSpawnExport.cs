using System;
using System.Globalization;
using System.IO;
using System.Text;
using UnityEditor;
using UnityEditor.SceneManagement;
using UnityEngine;

public static class MovementSpawnExport
{
    public static void Run()
    {
        if (!Application.isBatchMode) throw new Exception("Batch only");
        EditorSceneManager.NewScene(NewSceneSetup.EmptyScene, NewSceneMode.Single);
        var b=new StringBuilder("// Generated by MovementSpawnExport; re-export when authored spawn points change.\n#pragma once\n#include <string>\nnamespace MovementSpawns {\nstruct Spawn { const char* map; int side,slot; float x,y,z; };\ninline constexpr Spawn points[]={\n");
        string F(float n) => n.ToString("0.#########",CultureInfo.InvariantCulture)+"f";
        foreach(string map in new[]{"TestMap","Desert","Construction"})
        {
            var root=(GameObject)PrefabUtility.InstantiatePrefab(AssetDatabase.LoadAssetAtPath<GameObject>($"Assets/ProjectVector/Shared/Maps/Prefabs/{map}.prefab"));
            root.transform.SetPositionAndRotation(Vector3.zero,Quaternion.identity);
            var info=root.GetComponent<MapInfo>();
            for(byte side=0;side<2;side++) for(byte slot=0;slot<(side==0?info.attackSpawnPoints.Length:info.defendSpawnPoints.Length);slot++)
            {
                var p=info.GetSpawnPoint(side,slot).position;
                string N(float n) {string s=F(n);return s.Contains(".")?s:s.Replace("f",".0f");}
                b.Append($"{{\"{map}\",{side},{slot},{N(p.x)},{N(p.y)},{N(p.z)}}},\n");
            }
            UnityEngine.Object.DestroyImmediate(root);
        }
        b.Append("};\ninline const Spawn* Find(const std::string& map,int side,int slot){for(const auto& p:points)if(map==p.map && side==p.side && slot==p.slot)return &p;return nullptr;}\n}\n");
        File.WriteAllText(Path.Combine(Path.GetTempPath(),"VectorMovementSpawns.generated.h"),b.ToString());
        Debug.Log("MOVEMENT_SPAWN_EXPORT_PASS");
    }
}
